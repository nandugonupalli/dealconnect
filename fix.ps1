# ============================================================
#  DealConnect - Auto Fix Script
#  Usage: .\fix.ps1
# ============================================================

param(
    [switch]$SkipGit,
    [switch]$SkipDev,
    [switch]$Verbose
)

$ErrorActionPreference = "Continue"
$startTime = Get-Date

# Colors
function Write-Step { param($msg) Write-Host "`n? $msg" -ForegroundColor Cyan }
function Write-Ok { param($msg) Write-Host "  ? $msg" -ForegroundColor Green }
function Write-Warn { param($msg) Write-Host "  ??  $msg" -ForegroundColor Yellow }
function Write-Err { param($msg) Write-Host "  ? $msg" -ForegroundColor Red }

Write-Host @"

????????????????????????????????????????????????????????????
?         DealConnect - Auto Fix & Deploy Script           ?
?                    Version 1.0                           ?
????????????????????????????????????????????????????????????

"@ -ForegroundColor Magenta

# ????????????????????????????????????????????????????????????
# STEP 1: Remove BOM from all text files
# ????????????????????????????????????????????????????????????
Write-Step "Step 1/6: Removing BOM characters..."

$utf8NoBom = New-Object System.Text.UTF8Encoding $false
$bomCount = 0

$fileExtensions = @("*.json", "*.ts", "*.tsx", "*.js", "*.jsx", "*.css", "*.html", "*.md")

Get-ChildItem -Path "." -Recurse -Include $fileExtensions -File -ErrorAction SilentlyContinue |
    Where-Object {
        $_.FullName -notmatch "node_modules" -and
        $_.FullName -notmatch "\\dist\\" -and
        $_.FullName -notmatch "\\.git\\" -and
        $_.FullName -notmatch "\\.vite\\"
    } |
    ForEach-Object {
        try {
            $content = Get-Content $_.FullName -Raw -Encoding UTF8 -ErrorAction SilentlyContinue
            if ($content -and $content.Length -gt 0 -and $content[0] -eq [char]0xFEFF) {
                $content = $content.TrimStart([char]0xFEFF)
                [System.IO.File]::WriteAllText($_.FullName, $content, $utf8NoBom)
                $bomCount++
                if ($Verbose) { Write-Host "    Cleaned: $($_.Name)" -ForegroundColor Gray }
            }
        } catch { }
    }

Write-Ok "Removed BOM from $bomCount file(s)"

# ????????????????????????????????????????????????????????????
# STEP 2: Validate JSON files
# ????????????????????????????????????????????????????????????
Write-Step "Step 2/6: Validating JSON files..."

$jsonFiles = @("package.json", "tsconfig.json", "package-lock.json")
$jsonErrors = 0

foreach ($file in $jsonFiles) {
    if (Test-Path $file) {
        try {
            Get-Content $file -Raw | ConvertFrom-Json | Out-Null
            Write-Ok "$file is valid"
        } catch {
            Write-Err "$file is INVALID: $_"
            $jsonErrors++
        }
    }
}

if ($jsonErrors -gt 0) {
    Write-Err "Fix JSON errors above before continuing!"
    exit 1
}

# ????????????????????????????????????????????????????????????
# STEP 3: Verify all critical files exist
# ????????????????????????????????????????????????????????????
Write-Step "Step 3/6: Verifying critical files..."

$criticalFiles = @(
    "package.json",
    "tsconfig.json",
    "vite.config.ts",
    "tailwind.config.js",
    "postcss.config.js",
    "index.html",
    ".npmrc",
    "src/main.tsx",
    "src/App.tsx",
    "src/vite-env.d.ts",
    "src/assets/styles/globals.css",
    "src/components/layout/Navbar.tsx",
    "src/components/layout/Footer.tsx",
    "src/context/AuthContext.tsx",
    "src/context/CartContext.tsx",
    "src/context/ThemeContext.tsx",
    "src/routes/AppRoutes.tsx"
)

$missingFiles = @()
foreach ($file in $criticalFiles) {
    if (Test-Path $file) {
        Write-Ok "$file"
    } else {
        Write-Err "$file MISSING"
        $missingFiles += $file
    }
}

if ($missingFiles.Count -gt 0) {
    Write-Warn "$($missingFiles.Count) file(s) missing. Continuing anyway..."
}

# ????????????????????????????????????????????????????????????
# STEP 4: Verify import paths in public pages
# ????????????????????????????????????????????????????????????
Write-Step "Step 4/6: Checking import paths..."

$publicPages = @(
    "src/pages/public/HowItWorks.tsx",
    "src/pages/public/Pricing.tsx",
    "src/pages/public/ForManufacturers.tsx",
    "src/pages/public/ForDealers.tsx"
)

$fixedImports = 0
foreach ($file in $publicPages) {
    if (Test-Path $file) {
        $content = Get-Content $file -Raw
        $original = $content
        # Fix ../components/ to ../../components/
        $content = $content -replace "from '\.\./components/", "from '../../components/"
        $content = $content -replace 'from "\.\./components/', 'from "../../components/'
        
        if ($content -ne $original) {
            [System.IO.File]::WriteAllText("$PWD\$file", $content, $utf8NoBom)
            $fixedImports++
            Write-Ok "Fixed imports: $file"
        }
    }
}

if ($fixedImports -eq 0) {
    Write-Ok "All imports are correct"
} else {
    Write-Ok "Fixed $fixedImports file(s)"
}

# ????????????????????????????????????????????????????????????
# STEP 5: Clear caches
# ????????????????????????????????????????????????????????????
Write-Step "Step 5/6: Clearing caches..."

$caches = @(
    "node_modules\.vite",
    ".vite",
    "dist",
    "tsconfig.tsbuildinfo",
    ".tsbuildinfo"
)

foreach ($cache in $caches) {
    if (Test-Path $cache) {
        Remove-Item -Recurse -Force $cache -ErrorAction SilentlyContinue
        Write-Ok "Cleared: $cache"
    }
}

# ????????????????????????????????????????????????????????????
# STEP 6: Git operations (optional)
# ????????????????????????????????????????????????????????????
if (-not $SkipGit) {
    Write-Step "Step 6/6: Git operations..."
    
    $gitStatus = git status --porcelain 2>$null
    if ($gitStatus) {
        Write-Ok "Found changes to commit"
        
        git add .
        git commit -m "fix: auto-fix BOM, imports, and caches [$(Get-Date -Format 'yyyy-MM-dd HH:mm')]" 2>$null
        
        if ($LASTEXITCODE -eq 0) {
            Write-Ok "Committed changes"
            
            # Pull with rebase
            git pull origin main --rebase 2>$null
            
            # Push
            git push origin main 2>$null
            
            if ($LASTEXITCODE -eq 0) {
                Write-Ok "Pushed to GitHub"
            } else {
                Write-Warn "Push failed - resolve manually"
            }
        }
    } else {
        Write-Ok "No changes to commit"
    }
} else {
    Write-Warn "Skipped git operations (-SkipGit)"
}

# ????????????????????????????????????????????????????????????
# SUMMARY
# ????????????????????????????????????????????????????????????
$duration = (Get-Date) - $startTime

Write-Host @"

????????????????????????????????????????????????????????????
?                    ? ALL DONE!                          ?
????????????????????????????????????????????????????????????

  Duration:     $($duration.TotalSeconds.ToString('0.0'))s
  BOM removed:  $bomCount
  Imports fixed: $fixedImports
  Caches:       Cleared

  Next steps:
  1. In VS Code: Ctrl+Shift+P ? TypeScript: Restart TS Server
  2. Run: npm run dev
  3. Check: http://localhost:3000

"@ -ForegroundColor Green

# ????????????????????????????????????????????????????????????
# START DEV SERVER
# ????????????????????????????????????????????????????????????
if (-not $SkipDev) {
    Write-Host "?? Starting dev server...`n" -ForegroundColor Cyan
    npm run dev
} else {
    Write-Host "Run 'npm run dev' to start the server.`n" -ForegroundColor Yellow
}
